<!-- SUBNAV + STICKY CTA + SCHEDULER SCRIPTS -->
<script>
(function(){
  // Subnav active state
  const sections = ['preserve','clarify','upgrade','timeline','faq'].map(id => document.getElementById(id)).filter(Boolean);
  const links = document.querySelectorAll('[data-subnav]');
  const byId = href => document.querySelector(`a[href="#${href}"]`);
  const io = new IntersectionObserver(entries => {
    entries.forEach(e => {
      if (!e.isIntersecting) return;
      const id = e.target.id;
      links.forEach(a => a.classList.toggle('active', a.getAttribute('href') === '#'+id));
    });
  }, { rootMargin: '-45% 0px -50% 0px', threshold: 0 });
  sections.forEach(s => io.observe(s));

  // Sticky CTA after 25% scroll; hide when modal open
  const sticky = document.querySelector('[data-sticky-cta]');
  const scheduleEmbed = document.getElementById('scheduler-embed');
  const revealAfter = window.innerHeight * 0.25;
  let shown = false;
  window.addEventListener('scroll', () => {
    if (scheduleEmbed && !scheduleEmbed.hasAttribute('hidden')) return; // hide if modal open
    if (!shown && window.scrollY > revealAfter) { sticky.removeAttribute('hidden'); shown = true; }
  });

  // Scheduler modal open/close
  const openBtns = document.querySelectorAll('[data-open-scheduler]');
  const closeBtn = document.querySelector('[data-close-scheduler]');
  function openScheduler(e){
    if (e) e.preventDefault();
    const src = scheduleEmbed.querySelector('iframe').dataset.schedulerSrc;
    if (src && !scheduleEmbed.querySelector('iframe').src) scheduleEmbed.querySelector('iframe').src = src;
    scheduleEmbed.removeAttribute('hidden');
    document.body.style.overflow = 'hidden';
    sticky && sticky.setAttribute('hidden','');
  }
  function closeScheduler(e){
    if (e) e.preventDefault();
    scheduleEmbed.setAttribute('hidden','');
    document.body.style.overflow = '';
  }
  openBtns.forEach(b => b.addEventListener('click', openScheduler));
  closeBtn && closeBtn.addEventListener('click', closeScheduler);
  document.addEventListener('keydown', (e)=>{ if(e.key==='Escape' && scheduleEmbed && !scheduleEmbed.hasAttribute('hidden')) closeScheduler(); });

  // Focus styles for keyboard users
  function handleFirstTab(e){
    if(e.key==='Tab'){ document.body.classList.add('user-is-tabbing'); window.removeEventListener('keydown', handleFirstTab); }
  }
  window.addEventListener('keydown', handleFirstTab);
})();
</script>
